"""
Alert Management Module
========================

Collects, stores, and distributes alerts generated by the DetectionEngine.

Responsibilities:
  - Maintain an in-memory alert history (bounded deque).
  - Persist alerts to the SQLite database via the StorageManager.
  - Fan-out alerts to any number of subscribers (UI, logging, etc.).
  - Provide query helpers (latest N, by severity, by zone).
"""

from __future__ import annotations

import logging
import threading
from collections import deque
from dataclasses import dataclass, field
from typing import Callable, Optional

from src.core.detection import Alert, AlertSeverity, PresenceLevel

logger = logging.getLogger(__name__)

MAX_HISTORY = 500  # in-memory cap


class AlertManager:
    """
    Central alert bus.

    Usage
    -----
    >>> mgr = AlertManager()
    >>> mgr.subscribe(my_callback)       # register consumer
    >>> mgr.handle_alert(alert)          # feed from DetectionEngine
    >>> recent = mgr.get_recent(10)      # pull last 10 alerts
    """

    def __init__(self, max_history: int = MAX_HISTORY):
        self._history: deque[Alert] = deque(maxlen=max_history)
        self._subscribers: list[Callable[[Alert], None]] = []
        self._lock = threading.Lock()
        self._db_writer: Optional[Callable[[Alert], None]] = None

    # ---- subscription -----------------------------------------------------

    def subscribe(self, callback: Callable[[Alert], None]) -> None:
        """Add a subscriber that will receive every new alert."""
        self._subscribers.append(callback)

    def set_db_writer(self, writer: Callable[[Alert], None]) -> None:
        """
        Attach a database persistence callback.

        Called synchronously for every alert (the StorageManager should
        handle its own threading if needed).
        """
        self._db_writer = writer

    # ---- ingestion --------------------------------------------------------

    def handle_alert(self, alert: Alert) -> None:
        """
        Process an incoming alert: store, persist, distribute.

        Designed to be passed directly as a callback to
        :pymethod:`DetectionEngine.on_alert`.
        """
        with self._lock:
            self._history.append(alert)

        # Persist
        if self._db_writer:
            try:
                self._db_writer(alert)
            except Exception:
                logger.exception("Failed to persist alert to database")

        # Fan-out
        for sub in self._subscribers:
            try:
                sub(alert)
            except Exception:
                logger.exception("Alert subscriber error")

    # ---- queries ----------------------------------------------------------

    def get_recent(self, count: int = 20) -> list[Alert]:
        """Return the *count* most recent alerts (newest first)."""
        with self._lock:
            items = list(self._history)
        return list(reversed(items[-count:]))

    def get_by_severity(self, severity: AlertSeverity) -> list[Alert]:
        with self._lock:
            return [a for a in self._history if a.severity == severity]

    def get_by_zone(self, zone_id: str) -> list[Alert]:
        with self._lock:
            return [a for a in self._history if a.zone_id == zone_id]

    def get_critical(self) -> list[Alert]:
        return self.get_by_severity(AlertSeverity.CRITICAL)

    @property
    def total_count(self) -> int:
        return len(self._history)

    def clear(self) -> None:
        with self._lock:
            self._history.clear()
